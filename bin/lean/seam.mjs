/**
 * #5338: the machine form of an interface. A spike/epic `Interfaces` row whose signature cell is an HTTP route
 * (`POST /v1/search`), a function signature (`refund(job_id, amount_micro)`) or a typed payload / queue message
 * (`queue research.jobs {query, device, city, uule}`) is parsed into a `seam` and becomes (1) a generated contract test
 * that provider and consumer CI both run against the real source, nothing mocked, and (2) a deterministic precheck at
 * lane review (`seamFailures`), so a mismatch is flagged when the lane that causes it is reviewed, not at release review.
 * The checker itself is templates/contracts/seam-check.mjs (self-contained, copied next to the generated tests).
 * Pure except where an injected read/list is given; no LLM, gh or git here.
 */
import { OUTCOME_CODES } from "../engine/outcome-codes.mjs";
import { checkSeam, authMode, anchorMatches } from "../../templates/contracts/seam-check.mjs";

export { checkSeam, authMode };
export const SEAM_KINDS = ["symbol", "route", "payload"];
const IDENT = /^[A-Za-z_$][\w$]*$/;
const METHODS = /^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s+(\/[^\s`]*)/i;

const unTick = (s) => String(s ?? "").trim().replace(/^`+|`+$/g, "").trim();

function topSplit(s) {
  const out = []; let depth = 0, cur = "";
  for (const c of s) {
    if ("([{<".includes(c)) depth++; else if (")]}>".includes(c)) depth = Math.max(0, depth - 1);
    if (c === "," && depth === 0) { out.push(cur); cur = ""; } else cur += c;
  }
  if (cur.trim()) out.push(cur);
  return out.map((x) => x.trim()).filter(Boolean);
}

/** {kind, symbol|route|payload} for a signature cell with a machine form, else null. */
export function parseSeamForm(signature) {
  const t = unTick(signature);
  const r = METHODS.exec(t);
  if (r) return { kind: "route", route: { method: r[1].toUpperCase(), path: r[2].replace(/[.,;]+$/, "") } };
  const f = /^(?:(?:async|def|function|fn)\s+)?([A-Za-z_$][\w$.]*)\s*\(([^)]*)\)/.exec(t);
  if (f) {
    const name = f[1].split(".").at(-1);
    const params = [];
    for (const raw of topSplit(f[2])) {
      if (raw === "*" || raw === "/") continue;
      const variadic = /^(\*\*?|\.\.\.)/.test(raw);
      const m = /^([A-Za-z_$][\w$]*)(\?)?/.exec(raw.replace(/^(\*\*?|\.\.\.)/, ""));
      if (!m) return null;
      params.push({ name: m[1], optional: Boolean(m[2]) || /(^|[^=!<>])=(?!=)/.test(raw) || variadic, variadic });
    }
    if (IDENT.test(name)) return { kind: "symbol", symbol: { name, params } };
  }
  const p = /^(?:(?:queue|topic|message|payload|event)\s+)?(?:[\w.:\-/]+\s+)?\{([^}]*)\}/i.exec(t);
  if (p) {
    const fields = [...new Set(topSplit(p[1]).map((x) => /^["']?([A-Za-z_$][\w$]*)/.exec(x)?.[1]).filter(Boolean))];
    if (fields.length) return { kind: "payload", payload: { fields } };
  }
  return null;
}

/** Anchor cell tokens: `provider:path` / `consumer:path` set the side; a bare path is governed but on neither side. {all, provider, consumer}. */
export function roleAnchors(tokens) {
  const all = [], provider = [], consumer = [];
  for (const raw of tokens ?? []) {
    const m = /^(provider|consumer)\s*:\s*(.+)$/i.exec(String(raw).trim());
    const path = (m ? m[2] : String(raw)).trim();
    if (!path) continue;
    all.push(path);
    if (m?.[1].toLowerCase() === "provider") provider.push(path);
    if (m?.[1].toLowerCase() === "consumer") consumer.push(path);
  }
  return { all: [...new Set(all)], provider: [...new Set(provider)], consumer: [...new Set(consumer)] };
}

/** The stored seam of a decision from its parsed form and role anchors; null when no form or a side is undeclared. */
export function buildSeam(form, roles, auth) {
  if (!form || !roles?.provider?.length || !roles?.consumer?.length) return null;
  return { ...form, auth: String(auth ?? "").slice(0, 160), provider: roles.provider, consumer: roles.consumer };
}

/** The contract the checker and the generated test take, from a decision record with a `seam`. */
export const seamContract = (rec) => ({ v: 1, id: rec.id, kind: rec.seam.kind, boundary: String(rec.choice ?? "").slice(0, 160), auth: rec.seam.auth ?? "", [rec.seam.kind]: rec.seam[rec.seam.kind], provider: rec.seam.provider, consumer: rec.seam.consumer });

/** Source of `contracts/<id>.contract.test.mjs`: one node:test file that reads both sides' real source. */
export function renderSeamTest(contract) {
  const lit = JSON.stringify(contract, null, 2).replace(/</g, "\\u003c");
  return `// Generated by \`npx forgedock interfaces contract\` for interface decision ${contract.id} (forgedock #5338).
// Both sides of the seam run this file (\`node --test contracts/*.contract.test.mjs\`); it reads the real source and mocks nothing.
// Changing the interface means a \`supersedes\` decision and regenerating this file, not editing it by hand.
import { test } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { checkSeamAt, formatFindings } from "./seam-check.mjs";

const contract = ${lit};

test(\`interface \${contract.id}: \${contract.boundary}\`, () => {
  const r = checkSeamAt(contract, fileURLToPath(new URL("../", import.meta.url)));
  assert.equal(r.unchecked, undefined, r.unchecked);
  assert.equal(r.findings.length, 0, \`the provider and consumer disagree on \${contract.id}:\\n\${formatFindings(r.findings)}\`);
});
`;
}

/**
 * Lane-review failures: for every active decision with a `seam` whose anchors a changed file touches (and that the lane
 * does not supersede), run the checker on the lane's worktree. `read(path)`/`list()` give the worktree files. Pure.
 */
export function seamFailures({ records, changedFiles, read, list, superseded = [] }) {
  const gone = new Set(superseded), out = [];
  for (const rec of records ?? []) {
    if (!rec?.seam || rec.status === "superseded" || gone.has(rec.id)) continue;
    if (!(changedFiles ?? []).some((f) => (rec.anchors ?? []).some((a) => anchorMatches(a, f)))) continue;
    const r = checkSeam(seamContract(rec), { read, list });
    for (const f of r.findings) out.push({ code: OUTCOME_CODES.CONFORMANCE_PRESERVE_VIOLATED, kind: "interface_seam", detail: `decision ${rec.id} (${rec.choice.slice(0, 80)}): ${f.side}${f.file ? ` ${f.file}${f.line ? `:${f.line}` : ""}` : ""}: ${f.detail}; amend {kind:"decision", decision:{choice, anchors, supersedes:"${rec.id}"}, why} when the interface really changes` });
  }
  return out;
}
